"""Oversight Statement — one page, blank signature block for a HUMAN.

Signoff never signs. The accountable person field is left blank on purpose;
the owner signs offline. See OWNER/oversight-statement.md.
"""
from __future__ import annotations

from typing import TYPE_CHECKING

from signoff.render.appendix import APPENDIX_BANNER
from signoff.render.disclosure import active_banners, not_proof_text

if TYPE_CHECKING:  # pragma: no cover
    from signoff.model.evidence_pack import EvidencePack

_DASHES = "____________________________"


def render_statement_txt(pack: "EvidencePack") -> str:
    lines = [
        "OVERSIGHT STATEMENT — FOR HUMAN SIGNATURE",
        "",
        f"Pack id     : {pack.pack_id}",
        f"As-of       : {pack.as_of}",
        f"Chain head  : {pack.head}",
        f"Generated by: Signoff 0.1.0 (offline build, no model in the evidence path)",
        "",
        "Statement",
        "---------",
        "I attest that the oversight evidence in this pack was reconstructed",
        "from records our organisation supplied, that every mapping of a",
        "question to evidence was decided by a named human recorded in the",
        "mapping table, and that the gap list is accurate as of the as-of date.",
        "",
        "Accountable person (name) : " + _DASHES,
        "Role / organisation        : " + _DASHES,
        "Signature                  : " + _DASHES,
        "Date                       : " + _DASHES,
        "",
        "This statement is signed by a human. Signoff never signs on anyone's behalf.",
        "",
        APPENDIX_BANNER,
        "The appendix cross-reference in the pack is informational only; it never",
        "classifies your system and never claims compliance.",
    ]
    for banner in active_banners(pack.simulated, pack.unverified_rules):
        lines += ["", banner]
    lines += ["", not_proof_text()]
    return "\n".join(lines) + "\n"
